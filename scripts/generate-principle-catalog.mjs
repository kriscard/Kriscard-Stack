import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { frontmatterField, skillFrontmatter } from "./skill-frontmatter.mjs";

const scriptPath = fileURLToPath(import.meta.url);
const defaultRoot = resolve(dirname(scriptPath), "..");
const principleNames = [
  "principle-boundary-discipline",
  "principle-evidence-follows-the-commit",
  "principle-minimize-context",
  "principle-one-goal-per-pull-request",
  "principle-prove-real-behavior",
  "principle-stop-on-plan-drift",
];

/**
 * Read only the discovery fields owned by a principle skill's frontmatter.
 *
 * @param {string} contents
 * @param {string} path
 */
function parsePrinciple(contents, path) {
  const frontmatter = skillFrontmatter(contents, path);
  const name = frontmatterField(frontmatter, "name");
  const description = frontmatterField(frontmatter, "description");
  if (!name) throw new Error(`${path} has no principle name`);
  if (!description) throw new Error(`${path} has no principle description`);

  return { name, description };
}

/** @param {string} repositoryRoot */
async function readPrinciples(repositoryRoot) {
  const devRoot = resolve(repositoryRoot, "skills/dev");
  const discovered = (await readdir(devRoot, { withFileTypes: true }))
    .filter(
      (entry) => entry.isDirectory() && entry.name.startsWith("principle-"),
    )
    .map((entry) => entry.name)
    .sort();

  if (JSON.stringify(discovered) !== JSON.stringify(principleNames)) {
    throw new Error(
      `Expected exactly these principle skills: ${principleNames.join(", ")}; found: ${discovered.join(", ")}`,
    );
  }

  return Promise.all(
    principleNames.map(async (directory) => {
      const path = resolve(devRoot, directory, "SKILL.md");
      const principle = parsePrinciple(await readFile(path, "utf8"), path);
      if (principle.name !== directory) {
        throw new Error(
          `${path} declares ${principle.name}; expected ${directory}`,
        );
      }
      return principle;
    }),
  );
}

/** @param {{ name: string, description: string }[]} principles */
function renderCatalog(principles) {
  const entries = principles
    .map(
      ({ name, description }) =>
        `## \`${name}\`\n\n[SKILL.md](${name}/SKILL.md)\n\n${description}`,
    )
    .join("\n\n");

  return `<!-- Generated by scripts/generate-principle-catalog.mjs. Do not edit. -->\n\n# Engineering principle catalog\n\nUse these frontmatter descriptions to discover only the principles supported by evidence from the current task. Read a linked leaf skill in full before applying it.\n\n${entries}\n`;
}

/** @param {string} repositoryRoot */
async function expectedCatalog(repositoryRoot) {
  return renderCatalog(await readPrinciples(repositoryRoot));
}

/** @param {string[]} args */
function parseArguments(args) {
  let check = false;
  let repositoryRoot = defaultRoot;

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--root" && args[index + 1]) {
      repositoryRoot = resolve(args[index + 1]);
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }

  return { check, repositoryRoot };
}

/** @param {string[]} args */
async function main(args) {
  const { check, repositoryRoot } = parseArguments(args);
  const catalogPath = resolve(repositoryRoot, "skills/dev/PRINCIPLES.md");
  const expected = await expectedCatalog(repositoryRoot);

  if (check) {
    let actual;
    try {
      actual = await readFile(catalogPath, "utf8");
    } catch (error) {
      if (
        error &&
        typeof error === "object" &&
        "code" in error &&
        error.code === "ENOENT"
      ) {
        throw new Error(
          "Principle catalog is stale: skills/dev/PRINCIPLES.md is missing",
        );
      }
      throw error;
    }
    if (actual !== expected) {
      throw new Error(
        "Principle catalog is stale; run `node scripts/generate-principle-catalog.mjs`",
      );
    }
    console.log("Principle catalog is current");
    return;
  }

  await writeFile(catalogPath, expected);
  console.log("Generated skills/dev/PRINCIPLES.md");
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  await main(process.argv.slice(2));
}
